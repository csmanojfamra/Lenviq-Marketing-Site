/**
 * Regenerates `docs/seo-intent-map.md` from `src/lib/seo-intent.ts`.
 *
 * The map is code, not a document — see that file for why. This exists so the map can also be READ
 * by somebody who is not opening a TypeScript file: a marketer, or whoever is working through the
 * Search Console queue. The document is generated, never edited, and the banner says so.
 *
 *     npm run seo:map
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const { intentMap } = await import("../src/lib/seo-intent.ts");

const rows = intentMap();
const esc = (s) => String(s).replace(/\|/g, "\\|");

const byPriority = new Map();
for (const r of rows) {
  if (!byPriority.has(r.priority)) byPriority.set(r.priority, []);
  byPriority.get(r.priority).push(r);
}

const LABEL = {
  1: "Priority 1 — the pages the site exists to be found through",
  2: "Priority 2 — supporting commercial and conversion pages",
  3: "Priority 3 — topical depth",
  4: "Priority 4 — reference and navigational",
};

let out = `<!-- GENERATED by scripts/seo-intent-map.mjs. Do not edit — edit src/lib/seo-intent.ts. -->

# Search intent map

Every indexable URL on lenviq.in, what it is for, and the one query it exists to answer.

Two tests keep this honest: every URL in the sitemap must appear here, and **no two pages may claim
the same primary keyword**. A page added without a stated intent fails the suite; a page that would
compete with an existing one fails it by name.

${rows.length} URLs.

`;

for (const p of [1, 2, 3, 4]) {
  const list = byPriority.get(p) ?? [];
  if (!list.length) continue;
  out += `## ${LABEL[p]}\n\n`;
  out += `| URL | Type | Intent | Primary keyword | Secondary |\n|---|---|---|---|---|\n`;
  for (const r of list) {
    out += `| \`${esc(r.url)}\` | ${esc(r.type)} | ${esc(r.intent)} | **${esc(r.primary)}** | ${r.secondary.map(esc).join(" · ")} |\n`;
  }
  out += `\n`;
}

writeFileSync(join(process.cwd(), "docs/seo-intent-map.md"), out);
console.log(`docs/seo-intent-map.md — ${rows.length} URLs`);
