/**
 * Emit the route → help guide map into the product repository.
 *
 * ## Why it is emitted rather than written twice
 *
 * The product wants a "How this works" link on the screens a guide documents. It needs the slug,
 * and the slug lives here. Two hand-kept copies of a URL list drift the moment somebody renames a
 * guide — and the failure is silent and lands inside a customer's lending system, which is the
 * worst place to discover a 404.
 *
 * So this side emits and the product side asserts. It is the arrangement the design tokens and the
 * finance fixtures already use in this codebase: one owner, one generated file, and a test at the
 * far end that fails the build when the two disagree.
 *
 * Front matter is read directly rather than through `src/lib/help.ts`, so the script needs no
 * TypeScript loader and cannot be broken by a change to that module's imports.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, resolve, dirname } from "node:path";

const SRC = resolve(process.cwd(), "content/help");
const PRODUCT = resolve(process.cwd(), "..", "Fintrustsuite");
const OUT = join(PRODUCT, "src/lib/help/help-map.generated.json");

if (!existsSync(PRODUCT)) {
  console.log(`[help-map] ${PRODUCT} not found — skipping.`);
  process.exit(0);
}

const guides = [];
for (const file of readdirSync(SRC).filter((f) => f.endsWith(".md")).sort()) {
  const raw = readFileSync(join(SRC, file), "utf8");
  const m = /^---\n([\s\S]*?)\n---\n/.exec(raw);
  if (!m) continue;
  const meta = {};
  for (const line of m[1].split("\n")) {
    const i = line.indexOf(":");
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim().replace(/^["']|["']$/g, "");
  }
  if (meta.draft === "true") continue;
  guides.push({
    slug: file.replace(/\.md$/, ""),
    title: meta.title ?? file,
    section: meta.section ?? "Using Lenviq",
    order: meta.order ? Number(meta.order) : 999,
    route: meta.route || null,
  });
}

if (guides.length === 0) {
  console.error("[help-map] no published guides — refusing to emit an empty map.");
  process.exit(1);
}

const routed = guides.filter((g) => g.route);
const dupes = [...new Set(routed.map((g) => g.route).filter((r, i, a) => a.indexOf(r) !== i))];
if (dupes.length) {
  console.error(`[help-map] two guides claim the same screen: ${dupes.join(", ")}`);
  process.exit(1);
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  JSON.stringify(
    {
      note: "GENERATED by scripts/emit-help-map.mjs in Lenviq-Marketing-Site. Do not edit.",
      generatedFrom: "content/help/*.md",
      helpBase: "https://lenviq.in/help/",
      guides,
    },
    null,
    2,
  ) + "\n",
);
console.log(`[help-map] ${guides.length} guides, ${routed.length} mapped to a screen → ${OUT}`);
